export const FOODS: Preset[] = RAW.map(([name, kcal, f, c, p]) => ({ name, kcal, f, c, p }));

const norm = (s: string) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase();
const KEYS = FOODS.map(x => norm(x.name));

/** Tutte le parole cercate devono comparire nel nome (ignora accenti e maiuscole). */
export function searchFoods(q: string, max = 30): Preset[] {
  const w = norm(q).split(/\s+/).filter(Boolean);
  if (!w.length) return [];
  return FOODS.filter((_, i) => w.every(t => KEYS[i].includes(t))).slice(0, max);
}
